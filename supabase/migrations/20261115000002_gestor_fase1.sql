-- ===== CLIENTES =====
create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  name text not null,
  email text,
  phone text,
  document text,
  birth_date date,
  zip text, street text, number text, complement text, district text, city text, state text,
  tags text[] not null default '{}',
  notes text,
  source_platform text,
  external_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists uq_customers_store_email on public.customers (store_id, lower(email)) where email is not null and email <> '';
create unique index if not exists uq_customers_store_external on public.customers (store_id, source_platform, external_id) where external_id is not null;
create index if not exists idx_customers_store_document on public.customers (store_id, document);

-- ===== PEDIDOS =====
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  number bigint generated by default as identity,
  customer_id uuid references public.customers(id) on delete set null,
  channel text not null default 'manual',
  external_id text,
  status text not null default 'pending'
    check (status in ('pending','paid','processing','shipped','delivered','canceled','returned')),
  payment_status text not null default 'pending'
