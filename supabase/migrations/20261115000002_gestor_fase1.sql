-- ===== LIVRO DE ESTOQUE (schema erp) =====
create schema if not exists erp;

create table if not exists erp.stock_movements (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  variant_id uuid not null references public.product_variants(id) on delete cascade,
  type text not null check (type in ('initial','purchase','sale','return','adjustment','loss')),
  qty integer not null,
  balance_after integer,
  channel text not null default 'gestor',
  order_id uuid references public.orders(id) on delete set null,
  reference text,
  note text,
  idempotency_key text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  constraint stock_movements_sign check (
    qty <> 0 and (
      (type in ('sale','loss') and qty < 0)
      or (type in ('purchase','return') and qty > 0)
      or type in ('adjustment','initial')
    )
  )
);
create index if not exists idx_stock_mov_variant on erp.stock_movements (variant_id, created_at desc);
create index if not exists idx_stock_mov_store on erp.stock_movements (store_id, created_at desc);
create unique index if not exists uq_stock_mov_idem on erp.stock_movements (store_id, idempotency_key) where idempotency_key is not null;

alter table erp.stock_movements enable row level security;
drop policy if exists stock_mov_select on erp.stock_movements;
create policy stock_mov_select on erp.stock_movements for select using (public.is_store_owner_or_member(store_id));
drop policy if exists stock_mov_insert on erp.stock_movements;
create policy stock_mov_insert on erp.stock_movements for insert with check (public.is_store_owner_or_member(store_id));

grant usage on schema erp to authenticated, service_role;
grant select, insert on erp.stock_movements to authenticated;
grant all on erp.stock_movements to service_role;

-- Saldo inicial (antes das triggers existirem)
select set_config('erp.skip_apply', '1', true);
insert into erp.stock_movements (store_id, variant_id, type, qty, balance_after, channel, note)
select v.store_id, v.id, 'initial', v.stock, v.stock, 'migracao', 'Saldo inicial'
from public.product_variants v
where coalesce(v.stock, 0) <> 0
  and not exists (select 1 from erp.stock_movements m where m.variant_id = v.id);
select set_config('erp.skip_apply', '0', true);

-- Movimento aplica o saldo na variacao
create or replace function erp.apply_stock_movement()
returns trigger language plpgsql security definer set search_path = erp, public as $$
declare v_stock integer; v_store uuid;
begin
  if current_setting('erp.skip_apply', true) = '1' then return new; end if;
  select coalesce(stock, 0), store_id into v_stock, v_store
    from public.product_variants where id = new.variant_id for update;
  if not found then raise exception 'Variacao % nao encontrada', new.variant_id; end if;
  new.store_id := v_store;
  new.balance_after := v_stock + new.qty;
  perform set_config('erp.applying', '1', true);
  update public.product_variants set stock = new.balance_after, updated_at = now() where id = new.variant_id;
  perform set_config('erp.applying', '0', true);
  return new;
end $$;

drop trigger if exists trg_apply_stock_movement on erp.stock_movements;
create trigger trg_apply_stock_movement before insert on erp.stock_movements
  for each row execute function erp.apply_stock_movement();

-- Alteracao direta do saldo vira movimento (mantem o yampi-sync atual funcionando)
create or replace function erp.guard_variant_stock()
returns trigger language plpgsql security definer set search_path = erp, public as $$
begin
  if new.stock is not distinct from old.stock then return new; end if;
  if current_setting('erp.applying', true) = '1' then return new; end if;
  perform set_config('erp.skip_apply', '1', true);
  insert into erp.stock_movements (store_id, variant_id, type, qty, balance_after, channel, note)
  values (new.store_id, new.id, 'adjustment', coalesce(new.stock, 0) - coalesce(old.stock, 0), coalesce(new.stock, 0), 'direct', 'Alteracao direta do saldo');
  perform set_config('erp.skip_apply', '0', true);
  return new;
end $$;

drop trigger if exists trg_guard_variant_stock on public.product_variants;
create trigger trg_guard_variant_stock before update of stock on public.product_variants
  for each row execute function erp.guard_variant_stock();

-- Variacao nova com saldo vira saldo inicial
create or replace function erp.log_variant_insert()
returns trigger language plpgsql security definer set search_path = erp, public as $$
begin
  if coalesce(new.stock, 0) = 0 then return new; end if;
  perform set_config('erp.skip_apply', '1', true);
  insert into erp.stock_movements (store_id, variant_id, type, qty, balance_after, channel, note)
  values (new.store_id, new.id, 'initial', new.stock, new.stock, 'direct', 'Variacao criada com saldo');
  perform set_config('erp.skip_apply', '0', true);
  return new;
end $$;

drop trigger if exists trg_log_variant_insert on public.product_variants;
create trigger trg_log_variant_insert after insert on public.product_variants
  for each row execute function erp.log_variant_insert();

-- RPC usada pelo front
create or replace function public.gestor_stock_move(p_variant uuid, p_type text, p_qty integer, p_note text default null)
returns integer language plpgsql security definer set search_path = public, erp as $$
declare v_store uuid; v_bal integer;
begin
  select store_id into v_store from public.product_variants where id = p_variant;
  if v_store is null then raise exception 'Variacao nao encontrada'; end if;
  if not public.is_store_owner_or_member(v_store) then raise exception 'Sem acesso a esta loja'; end if;
  insert into erp.stock_movements (store_id, variant_id, type, qty, channel, note)
  values (v_store, p_variant, p_type, p_qty, 'gestor', p_note)
  returning balance_after into v_bal;
  return v_bal;
end $$;
revoke all on function public.gestor_stock_move(uuid, text, integer, text) from public, anon;
grant execute on function public.gestor_stock_move(uuid, text, integer, text) to authenticated;

